using Kiln;

namespace Gld.Kilngen;

public static class Emitter
{
    static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class",
        "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event",
        "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
        "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new",
        "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "record", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
        "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint",
        "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };

    public static string Emit(string json)
    {
        var (title, root) = SchemaJson.FromJson(json);
        if (root.Kind != SchemaKind.Struct)
            throw new KilnException("SCHEMA");
        if (string.IsNullOrEmpty(root.StructName))
            root = Schema.Struct(root.Fields, title);
        var structs = new List<Schema>();
        Collect(root, structs, []);
        var lines = new List<string>
        {
            "// <auto-generated/>",
            "#nullable enable",
            "using System.Collections.Generic;",
            "using Kiln;",
            "",
            "namespace Kiln.Generated;",
            "",
        };
        foreach (var schema in structs)
            EmitStruct(schema, lines);
        return string.Join('\n', lines);
    }

    static void Collect(Schema schema, List<Schema> found, HashSet<string> seen)
    {
        if (schema.Kind is SchemaKind.List or SchemaKind.Opt or SchemaKind.Dict)
        {
            Collect(schema.Item!, found, seen);
            return;
        }
        if (schema.Kind != SchemaKind.Struct || schema.StructName is null)
            return;
        foreach (var field in schema.Fields)
            Collect(field.Type, found, seen);
        if (seen.Add(schema.StructName))
            found.Add(schema);
    }

    static void EmitStruct(Schema schema, List<string> lines)
    {
        var name = schema.StructName!;
        lines.Add($"public sealed class {Ident(name)}");
        lines.Add("{");
        foreach (var field in schema.Fields)
            lines.Add($"    public {CsType(field.Type)} {Ident(field.Name)} {{ get; set; }}{Initializer(field.Type)}");
        lines.Add("");
        lines.Add("    public byte[] Encode() => KilnCodec.Encode(Schema(), ToValue());");
        lines.Add("");
        lines.Add($"    public static {Ident(name)} Decode(byte[] buf) => FromValue(KilnCodec.Decode(Schema(), buf));");
        lines.Add("");
        lines.Add("    public static int EncodedSize(IReadOnlyDictionary<string, object?> value) => KilnCodec.Encode(Schema(), value).Length;");
        lines.Add("");
        lines.Add("    public Dictionary<string, object?> ToValue()");
        lines.Add("    {");
        lines.Add("        var value = new Dictionary<string, object?>();");
        foreach (var field in schema.Fields)
            EmitStore(field, lines);
        lines.Add("        return value;");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public static {Ident(name)} FromValue(object? value)");
        lines.Add("    {");
        lines.Add("        var map = (IReadOnlyDictionary<string, object?>)value!;");
        lines.Add($"        var result = new {Ident(name)}();");
        foreach (var field in schema.Fields)
            EmitLoad(field, lines);
        lines.Add("        return result;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public static Kiln.Schema Schema() => Cached;");
        lines.Add("");
        lines.Add($"    static readonly Kiln.Schema Cached = Kiln.Schema.Struct(new Kiln.SchemaField[] {{ {string.Join(", ", schema.Fields.Select(field => $"new Kiln.SchemaField(\"{Esc(field.Name)}\", {SchemaExpr(field.Type)})"))} }}, \"{Esc(name)}\");");
        lines.Add("}");
        lines.Add("");
    }

    static void EmitStore(SchemaField field, List<string> lines)
    {
        var ident = Ident(field.Name);
        var key = $"value[\"{Esc(field.Name)}\"]";
        if (field.Type.Kind == SchemaKind.Struct)
            lines.Add($"        {key} = {ident}.ToValue();");
        else if (field.Type.Kind == SchemaKind.Opt && field.Type.Item!.Kind == SchemaKind.Struct)
            lines.Add($"        {key} = {ident} is null ? null : {ident}.ToValue();");
        else if (field.Type.Kind == SchemaKind.List && field.Type.Item!.Kind == SchemaKind.Struct)
            lines.Add($"        {key} = {ident}.ConvertAll(item => item.ToValue());");
        else if (field.Type.Kind == SchemaKind.Dict)
        {
            lines.Add($"        var _{ident} = new Dictionary<string, object?>();");
            lines.Add($"        foreach (var pair in {ident})");
            lines.Add($"            _{ident}[pair.Key] = {DictValueStore(field.Type.Item!, "pair.Value")};");
            lines.Add($"        {key} = _{ident};");
        }
        else
            lines.Add($"        {key} = {ident};");
    }

    static string DictValueStore(Schema inner, string expr) => inner.Kind switch
    {
        SchemaKind.Struct => $"{expr}.ToValue()",
        _ => expr,
    };

    static void EmitLoad(SchemaField field, List<string> lines)
    {
        var ident = Ident(field.Name);
        var access = $"map[\"{Esc(field.Name)}\"]";
        if (field.Type.Kind == SchemaKind.List)
        {
            lines.Add($"        result.{ident} = new {CsType(field.Type)}();");
            lines.Add($"        foreach (var item in (System.Collections.IList){access}!)");
            lines.Add($"            result.{ident}.Add({ReadExpr(field.Type.Item!, "item")});");
            return;
        }
        if (field.Type.Kind == SchemaKind.Dict)
        {
            lines.Add($"        result.{ident} = new {CsType(field.Type)}();");
            lines.Add($"        foreach (var pair in (IReadOnlyDictionary<string, object?>){access}!)");
            lines.Add($"            result.{ident}[pair.Key] = {ReadExpr(field.Type.Item!, "pair.Value")};");
            return;
        }
        if (field.Type.Kind == SchemaKind.Opt)
        {
            lines.Add($"        if ({access} is not null)");
            lines.Add($"            result.{ident} = {ReadExpr(field.Type.Item!, access)};");
            return;
        }
        lines.Add($"        result.{ident} = {ReadExpr(field.Type, access)};");
    }

    static string ReadExpr(Schema schema, string expr) => schema.Kind switch
    {
        SchemaKind.Bool => $"((bool){expr}!)",
        SchemaKind.I8 => $"System.Convert.ToSByte({expr})",
        SchemaKind.I16 => $"System.Convert.ToInt16({expr})",
        SchemaKind.I32 => $"System.Convert.ToInt32({expr})",
        SchemaKind.I64 or SchemaKind.Int => $"System.Convert.ToInt64({expr})",
        SchemaKind.U8 => $"System.Convert.ToByte({expr})",
        SchemaKind.U16 => $"System.Convert.ToUInt16({expr})",
        SchemaKind.U32 => $"System.Convert.ToUInt32({expr})",
        SchemaKind.U64 or SchemaKind.Uint => $"System.Convert.ToUInt64({expr})",
        SchemaKind.F32 => $"System.Convert.ToSingle({expr})",
        SchemaKind.F64 => $"System.Convert.ToDouble({expr})",
        SchemaKind.Str => $"((string){expr}!)",
        SchemaKind.Bytes => $"((byte[]){expr}!)",
        SchemaKind.Struct => $"{Ident(schema.StructName!)}.FromValue({expr})",
        _ => throw new KilnException("SCHEMA"),
    };

    static string CsType(Schema schema) => schema.Kind switch
    {
        SchemaKind.Bool => "bool",
        SchemaKind.I8 => "sbyte",
        SchemaKind.I16 => "short",
        SchemaKind.I32 => "int",
        SchemaKind.I64 or SchemaKind.Int => "long",
        SchemaKind.U8 => "byte",
        SchemaKind.U16 => "ushort",
        SchemaKind.U32 => "uint",
        SchemaKind.U64 or SchemaKind.Uint => "ulong",
        SchemaKind.F32 => "float",
        SchemaKind.F64 => "double",
        SchemaKind.Str => "string",
        SchemaKind.Bytes => "byte[]",
        SchemaKind.List => $"List<{CsType(schema.Item!)}>",
        SchemaKind.Opt => Nullable(schema.Item!),
        SchemaKind.Dict => $"Dictionary<string, {CsType(schema.Item!)}>",
        SchemaKind.Struct => Ident(schema.StructName!),
        _ => throw new KilnException("SCHEMA"),
    };

    static string Nullable(Schema inner)
    {
        var text = CsType(inner);
        return text.EndsWith('?') ? text : text + "?";
    }

    static string Initializer(Schema schema) => schema.Kind switch
    {
        SchemaKind.Str => " = \"\";",
        SchemaKind.Bytes => " = System.Array.Empty<byte>();",
        SchemaKind.List or SchemaKind.Dict or SchemaKind.Struct => " = new();",
        _ => "",
    };

    static string SchemaExpr(Schema schema) => schema.Kind switch
    {
        SchemaKind.Bool => "Kiln.Schema.Bool",
        SchemaKind.I8 => "Kiln.Schema.I8",
        SchemaKind.I16 => "Kiln.Schema.I16",
        SchemaKind.I32 => "Kiln.Schema.I32",
        SchemaKind.I64 => "Kiln.Schema.I64",
        SchemaKind.Int => "Kiln.Schema.Int",
        SchemaKind.U8 => "Kiln.Schema.U8",
        SchemaKind.U16 => "Kiln.Schema.U16",
        SchemaKind.U32 => "Kiln.Schema.U32",
        SchemaKind.U64 => "Kiln.Schema.U64",
        SchemaKind.Uint => "Kiln.Schema.Uint",
        SchemaKind.F32 => "Kiln.Schema.F32",
        SchemaKind.F64 => "Kiln.Schema.F64",
        SchemaKind.Str => "Kiln.Schema.Str",
        SchemaKind.Bytes => "Kiln.Schema.Bytes",
        SchemaKind.List => $"Kiln.Schema.List({SchemaExpr(schema.Item!)})",
        SchemaKind.Opt => $"Kiln.Schema.Opt({SchemaExpr(schema.Item!)})",
        SchemaKind.Dict => $"Kiln.Schema.Dict({SchemaExpr(schema.Item!)})",
        SchemaKind.Struct => $"{Ident(schema.StructName!)}.Schema()",
        _ => throw new KilnException("SCHEMA"),
    };

    static string Ident(string name) => Keywords.Contains(name) ? "@" + name : name;

    static string Esc(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
